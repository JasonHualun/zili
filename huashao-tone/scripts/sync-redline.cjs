// Copies the author's red-line word list into the extension. The Vault JSON stays the only
// source of truth: edit it there, then run `node scripts/sync-redline.cjs`.
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");

// Default: the author's Vault. Others pass their own JSON as an argument or set ZILI_DNA.
const SOURCE = process.env.ZILI_DNA || path.join(os.homedir(), "Documents", "Obsidian Vault", "LLM Wiki", "shared", "skills", "hualun-writing-core", "references", "hualun_author_dna.json");
const TARGET = path.join(__dirname, "..", "redline-data.js");

const dna = JSON.parse(fs.readFileSync(process.argv[2] || SOURCE, "utf8"));
const rules = dna.negative_constraints || {};
const data = {
  source: "hualun-writing-core/references/hualun_author_dna.json",
  syncedAt: new Date().toISOString().slice(0, 10),
  bannedWords: rules.banned_words || [],
  bannedPatterns: rules.banned_patterns || [],
  bannedStyles: rules.banned_styles || []
};
fs.writeFileSync(TARGET, `// Generated by scripts/sync-redline.cjs from ${data.source}. Do not edit by hand.\nglobalThis.ZiliRedline = ${JSON.stringify(data, null, 2)};\n`);
console.log(`redline-data.js: ${data.bannedWords.length} words, ${data.bannedPatterns.length} patterns, ${data.bannedStyles.length} styles`);
